use std::sync::atomic::{AtomicBool, Ordering};

static ENGLISH: AtomicBool = AtomicBool::new(false);

macro_rules! catalog {
    ($($key:ident => ($ru:literal, $en:literal)),+ $(,)?) => {
        #[derive(Clone, Copy)]
        #[allow(dead_code)] // Native and portable interfaces share this catalog.
        pub(super) enum Label { $($key),+ }

        pub(super) fn tr(key: Label) -> &'static str {
            translate(key, english())
        }

        fn translate(key: Label, english: bool) -> &'static str {
            let pair = match key { $(Label::$key => ($ru, $en)),+ };
            if english { pair.1 } else { pair.0 }
        }
    };
}

