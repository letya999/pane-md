pub(super) fn lint_label(code: &str) -> &'static str {
    tr(match code {
        "anchor-missing" => Label::LintAnchorMissing,
        "anchor-encoding" => Label::LintAnchorEncoding,
        "local-target-missing" => Label::LintTargetMissing,
        "local-target-unreadable" => Label::LintTargetUnreadable,
        "local-target-encoding" => Label::LintTargetEncoding,
        "review-anchor-missing" => Label::LintReviewMissing,
        "review-anchor-ambiguous" => Label::LintReviewAmbiguous,
        _ => Label::LintReviewRecord,
    })
}

pub(super) fn format_error(error: pane_md::markdown::FormatError) -> &'static str {
    use pane_md::markdown::FormatError::*;
    tr(match error {
        SelectText => Label::SelectFormatting,
        Unsupported => Label::FormatSourceHint,
        AroundSpaces => Label::SelectWithoutSpaces,
        ChooseParagraph => Label::ChooseParagraph,
        ChooseCell => Label::ChooseCell,
        TableSource => Label::TableSourceHint,
        LinkSource => Label::LinkSourceHint,
        LinkOneLine => Label::LinkOneLine,
        InvalidLink => Label::InvalidLink,
    })
}

pub(super) fn english() -> bool {
    ENGLISH.load(Ordering::Relaxed)
}

pub(super) fn set_language(english: bool) {
    ENGLISH.store(english, Ordering::Relaxed);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn workspace_commands_have_separate_mode_and_panel_labels() {
        for (english, read, reviews, edit, show, hide) in [
            (
                false,
                "Только чтение",
                "С комментариями",
                "Редактирование",
                "Развернуть оглавление",
                "Свернуть оглавление",
            ),
            (
                true,
                "Read only",
                "With comments",
                "Editing",
                "Show outline",
                "Hide outline",
            ),
        ] {
            for (label, dropdown, expected) in [
                (Label::View, Label::ViewDropdown, read),
                (Label::Review, Label::ReviewDropdown, reviews),
                (Label::Edit, Label::EditDropdown, edit),
            ] {
                assert_eq!(translate(label, english), expected);
                assert_eq!(translate(dropdown, english), format!("{expected} ▾"));
            }
            assert_eq!(translate(Label::ShowOutline, english), show);
            assert_eq!(translate(Label::HideOutline, english), hide);
        }
    }
}
